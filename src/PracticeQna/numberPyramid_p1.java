package PracticeQna;

public class numberPyramid_p1 {
    public static void main(String[]args){
        for (int i=1;i<=5;i++){
            for (int j=2;j<=i;j++){
                System.out.print(j);
            }
            System.out.println();
        }
//        2
//        23
//        234
//        2345
    }
}
