package Day_21_Strings;

public class stringsInJava {
    public static void main(String[]args){
        String name = "Rahul";
        char letter = 'A';
        System.out.println(name);
        System.out.println(letter);

        System.out.println(name.length());

//        For arrays:
//        numbers.length
//        For Strings:
//        name.length()
//        Notice the difference:
//        Array   → length
//        String  → length()
    }
}
