package Day_17_Arrays;

public class arraySize {
    public static void main(String[]args){
        // marks.length
        int [] marks = {80,90,70,88,78};
        System.out.println(marks.length);

//        5
//        Notice:
//        length = 5
//        but the last index is:
//        4
//        Because indexing starts from 0.
//        This gives us an important relationship:
//        Last index = length - 1
//        So if:
//        length = 5
//        then:
//        last index = 4
    }
}
