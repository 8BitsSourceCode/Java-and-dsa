package Day_4;

public class UnaryOperators {
    public static void main(String[] args){


//                ++    Increment
//                --    Decrement
//                +     Positive
//                -     Negative
//                !     NOT

        int x = 5;
        x++;
        System.out.println(x);
        int y = 5;
        --y;
        System.out.println(y);

        // pre increment
        int a = 5;
        System.out.println(a++);
        System.out.println(a);
        // post decrement
        int b = 5;
        System.out.println(++b);
        System.out.println(b++);



    }
}
